import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { choosePracticeTopic, idlePractice } from './practice-topic-helpers.mjs'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(10000)
const base = process.env.PRACTICE_UI_URL || 'http://127.0.0.1:5188/tests/ui/practice.html'
const output = '/tmp/tokensmith-model-selection-ui'
await mkdir(output, { recursive: true })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const chat = page.locator('.chat-frame')
const practice = page.locator('.practice-frame')
const picker = frame => frame.getByRole('button', { name: 'Choose chat model', exact: true })
const initial = async (suffix = '') => {
  await page.goto(`${base}?model-selection&run=${crypto.randomUUID()}${suffix}`)
  await picker(chat).waitFor()
  await page.waitForFunction(() => window.practiceTest.state().studyScope !== undefined)
}
const saved = async () => page.evaluate(() => window.practiceTest.state())
const waitModel = (id, modelId) => page.waitForFunction(({ id, modelId }) =>
  window.practiceTest.state().conversations.find(chat => chat.id === id)?.modelId === modelId, { id, modelId })
const choose = async (frame, name) => {
  await picker(frame).click()
  await frame.getByRole('button', { name, exact: true }).click()
}
const defaultModel = async id => {
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByLabel('Default model', { exact: true }).selectOption(id)
  await page.waitForFunction(id => window.practiceTest.state().settings.application.defaultModelId === id, id)
  await page.locator('.rail-nav').getByRole('button', { name: 'Chat', exact: true }).click()
}
try {
  await initial()
  await waitModel('chat-test', 'test')
  assert.equal('selectedModelId' in await saved(), false)
  await chat.getByRole('button', { name: 'Local conversation', exact: true }).click()
  await choose(chat, 'cloud-test')
  await waitModel('a', 'cloud')
  await chat.getByRole('button', { name: 'Cloud conversation', exact: true }).click()
  await choose(chat, 'ui-test')
  await waitModel('b', 'test')
  assert.equal((await saved()).settings.application.defaultModelId, 'test')
  assert.equal((await saved()).selectedEmbeddingModelId, 'test')
  await page.reload()
  await chat.getByRole('button', { name: 'Local conversation', exact: true }).click()
  assert.match(await picker(chat).innerText(), /cloud-test/)
  await chat.getByRole('button', { name: 'Cloud conversation', exact: true }).click()
  assert.match(await picker(chat).innerText(), /ui-test/)
  await picker(chat).click()
  assert.equal(await chat.getByRole('button', { name: 'search-only', exact: true }).count(), 0)
  await page.screenshot({ path: `${output}/picker-desktop.png` })
  await page.keyboard.press('Escape')

  await defaultModel('cloud')
  await waitModel('b', 'test')
  await chat.getByRole('button', { name: 'New Chat', exact: true }).click()
  await page.waitForFunction(() => { const s = window.practiceTest.state(); return s.conversations.find(c => c.id === s.activeConversationId)?.modelId === 'cloud' })
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  assert.match(await picker(practice).innerText(), /cloud-test/)
  await choose(practice, 'ui-test')
  await choosePracticeTopic(page)
  await practice.getByLabel('Your answer', { exact: true }).waitFor()
  const session = (await saved()).practice.sessions[0]
  assert.equal(session.modelId, 'test')
  assert.equal(session.modelSettings.contextLength, 8192)
  assert.equal(await picker(practice).isDisabled(), true)
  await idlePractice(page)
  await practice.getByRole('button', { name: 'Chat about this question', exact: true }).click()
  await page.waitForFunction(() => { const s = window.practiceTest.state(); return s.conversations.find(c => c.id === s.activeConversationId)?.practiceReference })
  assert.match(await picker(chat).innerText(), /ui-test/)
  assert.equal((await saved()).settings.application.defaultModelId, 'cloud')

  await page.evaluate(() => window.practiceTest.removeLocalModel())
  await chat.getByRole('status').filter({ hasText: "This chat's model is unavailable" }).waitFor()
  assert.match(await picker(chat).innerText(), /Model unavailable/)
  assert.equal(await chat.getByRole('button', { name: 'Send message', exact: true }).isDisabled(), true)
  await chat.getByRole('button', { name: 'Removed model conversation', exact: true }).click()
  assert.match(await picker(chat).innerText(), /Model unavailable/)
  await chat.getByRole('button', { name: 'Disconnected conversation', exact: true }).click()
  await chat.getByRole('button', { name: 'Enter API key', exact: true }).waitFor()
  assert.match(await picker(chat).innerText(), /cloud-disconnected/)
  await page.screenshot({ path: `${output}/disconnected-desktop.png` })
  await page.evaluate(() => window.practiceTest.disconnectCloud())
  await page.reload()
  await chat.getByRole('button', { name: 'Local conversation', exact: true }).click()
  assert.match(await picker(chat).innerText(), /cloud-test/)
  await chat.getByRole('button', { name: 'Enter API key', exact: true }).waitFor()
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await practice.getByText("This session's model is unavailable. Your questions and answers are saved.").waitFor()
  assert.equal((await saved()).practice.sessions[0].modelId, 'test')

  await initial('&slow-search&suggestions')
  await chat.getByRole('button', { name: 'Local conversation', exact: true }).click()
  await chat.getByLabel('Message', { exact: true }).fill('Why keep the ancestor path?')
  await chat.getByRole('button', { name: 'Send message', exact: true }).click()
  await page.waitForFunction(() => window.practiceTest.calls.some(call => call.kind === 'search'))
  await defaultModel('cloud')
  await page.waitForFunction(() => window.practiceTest.calls.some(call => call.kind === 'discussion'))
  const request = await page.evaluate(() => window.practiceTest.calls.find(call => call.kind === 'discussion').request)
  assert.equal(request.model.id, 'test')
  assert.equal(request.modelSettings.contextLength, 8192)
  await page.waitForFunction(() => window.practiceTest.state().conversations.find(c => c.id === 'a').messages.some(m => m.role === 'assistant'))
  await chat.getByLabel('Message', { exact: true }).fill('Why is that needed?')
  await chat.getByRole('button', { name: 'Send message', exact: true }).click()
  await page.waitForFunction(() => window.practiceTest.calls.some(call => call.kind === 'rewrite'))
  assert.equal(await page.evaluate(() => window.practiceTest.calls.find(call => call.kind === 'rewrite').request.model.id), 'test')
  await page.waitForFunction(() => window.practiceTest.calls.filter(call => call.kind === 'discussion').length === 2)
  await page.waitForFunction(() => window.practiceTest.state().conversations.find(c => c.id === 'a').messages.filter(m => m.role === 'assistant').length === 2)
  await choose(chat, 'cloud-test')
  await chat.getByLabel('Message', { exact: true }).fill('How would a split change it?')
  await chat.getByRole('button', { name: 'Send message', exact: true }).click()
  await page.waitForFunction(() => window.practiceTest.calls.filter(call => call.kind === 'discussion').length === 3)
  const cloudRequest = await page.evaluate(() => window.practiceTest.calls.filter(call => call.kind === 'discussion').at(-1).request)
  assert.equal(cloudRequest.model.id, 'cloud')
  assert.equal(cloudRequest.modelSettings.contextLength, 16384)

  await page.setViewportSize({ width: 390, height: 844 })
  await initial()
  await picker(chat).click()
  await page.screenshot({ path: `${output}/picker-mobile.png` })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.equal(await chat.getByRole('button', { name: 'cloud-test', exact: true }).isVisible(), true)
  assert.notEqual(await picker(chat).getAttribute('aria-controls'), await practice.locator('[aria-label="Choose chat model"]').getAttribute('aria-controls'))

  await page.setViewportSize({ width: 1440, height: 1000 })
  for (const suffix of ['', '?empty']) {
    await page.goto(`${base.replace('practice.html', 'cloud-generators.html')}${suffix}`)
    await picker(chat).click()
    await chat.locator('.chat-model-menu').getByRole('button', { name: 'Connect a cloud model', exact: true }).click()
    await page.getByRole('button', { name: /^OpenAI Connect with/ }).click()
    await page.getByLabel('OpenAI API key', { exact: true }).fill('demo-key')
    await page.getByRole('button', { name: 'Connect and find models', exact: true }).click()
    await page.getByRole('radio', { name: 'gpt-4.1-mini', exact: true }).check()
    await page.getByRole('button', { name: 'Use this model', exact: true }).click()
    await page.waitForFunction(() => { const s = window.cloudTest.state(); return s.conversations.find(c => c.id === s.activeConversationId)?.modelId.startsWith('cloud:') })
    const state = await page.evaluate(() => window.cloudTest.state())
    const active = state.conversations.find(c => c.id === state.activeConversationId)
    assert.equal(state.settings.application.defaultModelId, suffix ? active.modelId : 'gemma')
    assert.equal(state.conversations.find(c => c.id === 'cloud-ui-test').modelId, suffix ? '' : 'gemma')
    assert.equal(state.selectedEmbeddingModelId, 'nomic')
    assert.match(await picker(chat).innerText(), /gpt-4.1-mini/)
  }
  assert.deepEqual(errors, [])
  console.log('Model selection UI passed: independent chats, reload, defaults, missing/disconnected models, Practice isolation and handoff, pending requests, rewrite/generation settings, desktop/mobile picker, cloud setup and first-run default.')
  console.log(`Screenshots: ${output}`)
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` })
  console.error(await page.locator('body').innerText())
  throw error
} finally { await browser.close() }
