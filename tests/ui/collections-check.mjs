import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH })
const page = await browser.newPage()
page.setDefaultTimeout(10000)
const base = process.env.PRACTICE_UI_URL || 'http://127.0.0.1:5197/tests/ui/practice.html'
const output = '/private/tmp/tokensmith-collections-ui'; await mkdir(output, { recursive: true })
const errors = []; page.on('pageerror', error => errors.push(error.message))
const library = page.locator('.collection-library')
const chat = page.locator('.chat-frame')
const practice = page.locator('.practice-frame')
const openLibrary = () => page.locator('.rail-nav').getByRole('button', { name: 'Libraries', exact: true }).click()
const openChat = () => page.locator('.rail-nav').getByRole('button', { name: 'Chat', exact: true }).click()
const row = name => library.locator('.library-collection-row').filter({ has: page.getByRole('button', { name, exact: true }) })
const saved = () => page.evaluate(() => window.practiceTest.state())
try {
  for (const [name, viewport] of Object.entries({ desktop: { width: 1440, height: 1000 }, mobile: { width: 390, height: 844 } })) {
    await page.setViewportSize(viewport)
    await page.goto(`${base}?collections&saved-topics&slow-model&run=${crypto.randomUUID()}`)
    await chat.getByRole('button', { name: 'Practice', exact: true }).waitFor()
    await page.waitForFunction(() => window.practiceTest.state().studyScope?.length === 2)
    await openLibrary()
    assert.equal(await library.getByRole('heading', { name: 'Libraries', exact: true }).count(), 1)
    await library.locator('.collection-header').getByRole('button', { name: 'Open library', exact: true }).click()
    await row('Poetry course').getByRole('button', { name: 'Close library', exact: true }).waitFor()
    assert.equal((await saved()).materials.length, 2)
    await page.evaluate(() => { window.collectionTest.pickPath = '/bad-folder' })
    await library.locator('.collection-header').getByRole('button', { name: 'Open library', exact: true }).click()
    await library.getByRole('alert').filter({ hasText: 'saved TokenSmith library' }).waitFor()
    assert.equal((await saved()).materials.length, 2)
    await row('Poetry course').getByRole('button', { name: 'Close library', exact: true }).click()
    await row('Poetry course').getByRole('button', { name: 'Open library', exact: true }).waitFor()
    await page.reload(); await openLibrary()
    await row('Poetry course').getByRole('button', { name: 'Open library', exact: true }).waitFor()
    await row('Database course').getByRole('button', { name: 'View documents', exact: true }).click()
    await library.getByRole('button', { name: 'Add documents', exact: true }).waitFor()
    await page.screenshot({ path: `${output}/${name}-collection.png` })

    // Answer generation keeps running when opening Library, then stops on unloading its collection.
    await openChat()
    await chat.getByLabel('Message', { exact: true }).fill('Why keep the ancestor path?')
    await chat.getByRole('button', { name: 'Send message', exact: true }).click()
    await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'discussion'))
    await openLibrary()
    await row('Database course').getByRole('button', { name: 'Close library', exact: true }).click()
    await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'cancel'))
    await openChat()
    await page.waitForTimeout(2200)
    assert.equal((await saved()).conversations.flatMap(c => c.messages).filter(m => m.role === 'assistant').length, 0, 'Late answers from unloaded collections must not publish')
    assert.equal(await chat.getByRole('button', { name: 'Send message', exact: true }).isDisabled(), true)
    await openLibrary()
    await row('Database course').getByRole('button', { name: 'Open library', exact: true }).click()
    await openChat()

    // Saved collection topics bypass the topic inference call.
    await chat.getByRole('button', { name: 'Practice', exact: true }).click()
    await practice.getByRole('button', { name: 'B+ trees', exact: true }).waitFor()
    assert.equal(await page.evaluate(() => window.practiceTest.calls.filter(c => c.kind === 'topics').length), 0)
    await practice.getByRole('button', { name: 'B+ trees', exact: true }).click()
    await practice.getByLabel('Your answer', { exact: true }).waitFor()
    await practice.getByRole('button', { name: 'True', exact: true }).click()
    await page.waitForFunction(() => window.practiceTest.calls.filter(c => c.kind === 'true_false_question').length === 2)
    await openLibrary()
    await row('Database course').getByRole('button', { name: 'Close library', exact: true }).click()
    await openChat()
    await page.waitForTimeout(2200)
    assert.equal((await saved()).practice.sessions[0].questions.length, 1, 'Late next question must not publish')
    assert.equal((await saved()).practice.sessions[0].questions[0].attempts.length, 1)
    await practice.getByText('Open the library to continue this practice.', { exact: true }).waitFor()
    await openLibrary()
    await row('Database course').getByRole('button', { name: 'Open library', exact: true }).click()
    await openChat()
    await practice.getByRole('button', { name: 'Retry question', exact: true }).click()
    await page.waitForFunction(() => window.practiceTest.state().practice.sessions[0].questions.length === 2)

    await openLibrary()
    await library.getByRole('button', { name: 'New library', exact: true }).click()
    await library.getByLabel('Name', { exact: true }).fill('New course')
    await library.getByRole('button', { name: 'Add documents', exact: true }).click()
    assert.equal(await library.getByText('notes.md', { exact: true }).count(), 1)
    assert.equal(await library.getByText('handout.pdf', { exact: true }).count(), 1)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `${output}/${name}-new-library-form.png` })
    await library.getByRole('button', { name: 'Create library', exact: true }).click()
    await library.getByRole('heading', { name: 'New course', exact: true }).waitFor()
    await library.getByRole('button', { name: 'Add documents', exact: true }).waitFor()
    await library.getByRole('button', { name: 'Read', exact: true }).first().waitFor()
    assert.equal(await library.getByRole('button', { name: 'Read', exact: true }).count(), 2)
    assert.doesNotMatch(await library.innerText(), /index|folder|collection/i)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.screenshot({ path: `${output}/${name}-new-collection.png` })
  }
  assert.deepEqual(errors, [])
  console.log('Collection UI passed: load/unload/reload, invalid folders, persisted state, scoped Chat/Practice cancellation with late-result rejection, saved topics without inference, preserved attempts, retry after reloading, creation and desktop/mobile layout.')
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` })
  console.error(await page.locator('body').innerText())
  throw error
} finally { await browser.close() }
