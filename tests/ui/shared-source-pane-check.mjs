import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { choosePracticeTopic, idlePractice, reviewPracticeQuestion } from './practice-topic-helpers.mjs'

// Real App and shared pane, deterministic bridge; no models or personal app data.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(12000)
const origin = process.env.SOURCE_PANE_UI_URL || 'http://127.0.0.1:5198'
const output = '/tmp/tokensmith-shared-source-pane'
await mkdir(output, { recursive: true })
const errors = []; page.on('pageerror', e => errors.push(e.message))
const chat = page.locator('.chat-frame'), practice = page.locator('.practice-frame')
const pane = frame => frame.getByRole('complementary', { name: 'Source passage', exact: true })
const reader = page.getByRole('dialog', { name: 'Source Markdown viewer' })
const pdf = page.getByRole('dialog', { name: 'Source PDF viewer' })
const practiceSession = () => page.evaluate(() => window.practiceTest.state().practice.sessions[0])
const practiceOpen = async flags => {
  await page.goto(`${origin}/tests/ui/practice.html?run=${crypto.randomUUID()}&practice${flags}`)
  await choosePracticeTopic(page)
}
const chatOpen = async flags => {
  await page.goto(`${origin}/tests/ui/generation-progress.html?preview=markdown&mixed${flags}`)
  await page.locator('#reset').click()
  await chat.getByLabel('Message', { exact: true }).fill('What does atomicity guarantee?')
  await chat.locator('.send-button').click()
  await pane(chat).waitFor()
  await page.waitForFunction(() => document.querySelector('#metrics')?.textContent.includes('1 pending'))
}
const back = frame => pane(frame).getByRole('button', { name: 'Sources and documents', exact: true }).click()
const openDocument = frame => pane(frame).getByRole('button', { name: 'Open document', exact: true }).click()
const noOverlay = async () => assert.equal(await page.getByRole('dialog').count(), 0)
const fits = async frame => {
  const boxes = await frame.evaluate(el => {
    const main = el.querySelector('.chat-main, .practice-main').getBoundingClientRect()
    const pane = el.querySelector('.study-source-pane').getBoundingClientRect()
    const passage = el.querySelector('.source-pane-passage').getBoundingClientRect()
    return { overlap: main.right > pane.left + 1 && main.left < pane.right - 1 && main.bottom > pane.top + 1 && main.top < pane.bottom - 1,
      height: passage.height, overflow: document.documentElement.scrollWidth > innerWidth + 1 }
  })
  assert.equal(boxes.overlap, false, 'Reading must not cover the conversation')
  assert.ok(boxes.height > 60, 'Passage must have usable height')
  assert.equal(boxes.overflow, false)
}
try {
  await chatOpen('&long-source')
  await noOverlay()
  assert.match(await pane(chat).innerText(), /Passage 1/)
  assert.equal(await pane(chat).getByRole('button', { name: /Keep open|Return to chat/ }).count(), 0)
  await pane(chat).getByText('Related question', { exact: true }).click()
  assert.match(await pane(chat).innerText(), /What does atomicity guarantee\?/)
  const passage = pane(chat).getByRole('region', { name: 'Passage text' })
  await passage.evaluate(el => { el.scrollTop = 170; window.savedPassage = el })
  assert.ok(await passage.evaluate(el => el.scrollTop > 0))
  const input = chat.getByLabel('Message', { exact: true })
  await input.fill('My next question')
  assert.equal(await chat.locator('.send-button').isDisabled(), true)
  await input.focus()
  await page.locator('#answer').evaluate(el => el.click())
  await chat.getByText(/Completed answer:/).waitFor()
  assert.equal(await input.evaluate(el => document.activeElement === el), true, 'Answer arrival must not steal typing focus')
  assert.equal(await passage.evaluate(el => el === window.savedPassage && el.scrollTop === 170), true)
  await page.locator('#finish').click()
  await pane(chat).getByRole('button', { name: 'Next source', exact: true }).click()
  await pane(chat).getByText('Source 2 of 4', { exact: true }).waitFor()
  await openDocument(chat)
  await pdf.waitFor()
  await pdf.getByRole('button', { name: 'Back to cited page', exact: true }).click()
  await pdf.getByRole('button', { name: 'Close PDF viewer' }).click()
  assert.equal(await pane(chat).isVisible(), true)
  await pane(chat).getByRole('button', { name: 'Next source', exact: true }).click()
  await openDocument(chat)
  await reader.waitFor()
  await reader.getByRole('button', { name: 'Back to passage', exact: true }).click()
  await page.getByRole('button', { name: 'Close Markdown viewer' }).click()
  await fits(chat)
  await page.screenshot({ path: `${output}/chat-desktop.png` })
  await pane(chat).getByRole('button', { name: 'Close source pane' }).click()
  await chat.getByRole('button', { name: '4 Sources', exact: true }).click()
  await chat.locator('.source-tray-card').first().click()
  await pane(chat).waitFor()
  for (const width of [1100, 866, 390]) {
    await page.setViewportSize({ width, height: 1000 })
    await fits(chat)
    await input.fill(`Draft at ${width}`)
    await page.screenshot({ path: `${output}/chat-${width}.png` })
  }
  console.log('PASS Chat: persistent passage/scroll, composer focus, PDF and Markdown readers, manual reopening, responsive layout')

  await page.setViewportSize({ width: 1440, height: 1000 })
  await chatOpen('&slow-source')
  await openDocument(chat)
  await pane(chat).getByRole('button', { name: 'Next source', exact: true }).click()
  await page.locator('#source').click()
  await page.locator('#finish').click()
  await noOverlay()
  assert.match(await pane(chat).innerText(), /Source 2 of 4/)
  await chatOpen('')
  await pane(chat).getByRole('button', { name: 'Close source pane' }).click()
  await page.locator('#finish').click()
  assert.equal(await pane(chat).count(), 0)
  console.log('PASS dismissal and late full-document loads cannot reopen or replace the pane')

  await practiceOpen('&show-sources&preview-sources&slow-model&many-sources')
  await pane(practice).waitFor()
  assert.equal(await practice.getAttribute('aria-busy'), 'true')
  await noOverlay()
  assert.equal(await page.evaluate(() => window.practiceTest.calls.filter(c => c.kind === 'read-source').length), 0)
  const expected = await page.evaluate(() => window.practiceTest.calls.find(c => c.kind === 'true_false_question').request.retrievedSources[0].context)
  const sourceCount = await page.evaluate(() => window.practiceTest.calls.find(c => c.kind === 'true_false_question').request.retrievedSources.length)
  assert.equal(sourceCount, 4, 'Practice supplies the focus passage and at most three companions')
  assert.equal(await pane(practice).getByRole('region', { name: 'Passage text' }).innerText(), expected)
  await pane(practice).getByRole('button', { name: 'Next source', exact: true }).click()
  await idlePractice(page)
  await pane(practice).getByText(`Source 2 of ${sourceCount}`, { exact: true }).waitFor()
  await fits(practice)
  await page.screenshot({ path: `${output}/practice-desktop.png` })
  await openDocument(practice); await reader.waitFor()
  await page.getByRole('button', { name: 'Close Markdown viewer' }).click()
  await practice.getByRole('button', { name: 'True', exact: true }).click()
  await page.waitForFunction(() => window.practiceTest.state().practice.sessions[0].questions[0].attempts.length === 1)
  assert.equal((await practiceSession()).questions[0].attempts[0].assisted, false)
  await idlePractice(page)
  await reviewPracticeQuestion(page, 1)
  assert.equal(await pane(practice).count(), 0, 'Reviewing another question clears the previous passage')
  await practice.locator('.source-tray-card').first().click()
  await pane(practice).getByText('Related question', { exact: true }).click()
  assert.match(await pane(practice).innerText(), /True\/False:/)
  await page.reload()
  assert.equal((await practiceSession()).questions[0].attempts[0].assisted, false)
  console.log('PASS Practice: matching evidence before generation, selection persists, independent mastery, historical sources and reload')

  await practiceOpen('&show-sources&source-error')
  await idlePractice(page)
  assert.equal(await pane(practice).count(), 0, 'Read while waiting disabled')
  await practice.locator('.source-tray-card').first().click()
  await openDocument(practice)
  await pane(practice).getByRole('alert').waitFor()
  assert.match(await pane(practice).getByRole('alert').innerText(), /Test source read failed/)
  await openDocument(practice); await reader.waitFor()
  await page.getByRole('button', { name: 'Close Markdown viewer' }).click()
  await back(practice)
  await practice.getByRole('button', { name: 'Chat', exact: true }).click()
  assert.equal(await pane(practice).count(), 0)
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await practice.locator('.source-tray-card').first().waitFor()
  console.log('PASS optional reader errors/retry, preference, and isolation between modes')

  for (const receiveHelp of [false, true]) {
    await practiceOpen('&show-sources')
    await idlePractice(page)
    await practice.getByRole('button', { name: 'Chat about this question', exact: true }).click()
    if (receiveHelp) {
      await chat.getByLabel('Message', { exact: true }).fill('Why keep the ancestor path?')
      await chat.getByLabel('Message', { exact: true }).press('Enter')
      await page.waitForFunction(() => window.practiceTest.state().practice.sessions[0].observations.some(e => e.kind === 'help_shown'))
    }
    await chat.getByRole('button', { name: 'Practice', exact: true }).click()
    await practice.getByRole('button', { name: 'True', exact: true }).click()
    await idlePractice(page)
    assert.equal((await practiceSession()).questions[0].attempts[0].assisted, receiveHelp)
  }
  console.log('PASS only a received Chat explanation counts as help')

  await practiceOpen('&show-sources&preview-sources&slow-model')
  await pane(practice).waitFor()
  await pane(practice).getByRole('button', { name: 'Close source pane' }).click()
  await idlePractice(page)
  assert.equal(await pane(practice).count(), 0)
  await practiceOpen('&show-sources&preview-sources&slow-model')
  await pane(practice).waitFor()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await idlePractice(page)
  assert.equal(await pane(practice).count(), 0)
  await page.getByRole('checkbox', { name: 'Read while waiting', exact: true }).uncheck()
  await page.reload()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  assert.equal(await page.getByRole('checkbox', { name: 'Read while waiting', exact: true }).isChecked(), false)
  await practiceOpen('')
  await idlePractice(page)
  assert.equal(await practice.locator('.source-tray-card').count(), 0)
  assert.equal(await pane(practice).count(), 0)
  console.log('PASS dismissal, navigation, and persisted source preferences')

  await page.setViewportSize({ width: 390, height: 844 })
  await practiceOpen('&show-sources&preview-sources&slow-model')
  await pane(practice).waitFor()
  await fits(practice)
  await idlePractice(page)
  await practice.getByRole('button', { name: 'True', exact: true }).waitFor()
  await page.screenshot({ path: `${output}/practice-mobile.png` })
  assert.deepEqual(errors, [])
  console.log('PASS narrow Practice layout and no browser errors')
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` })
  console.error(await page.locator('body').innerText())
  throw error
} finally { await browser.close() }
