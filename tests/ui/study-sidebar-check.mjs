import { choosePracticeTopic, idlePractice, reviewPracticeQuestion, answerThenReview, advancePractice } from './practice-topic-helpers.mjs'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH })
const base = process.env.PRACTICE_UI_URL || 'http://127.0.0.1:5188/tests/ui/practice.html'
const output = '/tmp/tokensmith-study-sidebar-ui'
await mkdir(output, { recursive: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(10000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
const chat = page.locator('.chat-frame')
const practice = page.locator('.practice-frame')
const button = (frame, name) => frame.getByRole('button', { name, exact: true })
const sidebar = frame => frame.locator('.study-sidebar')
const initial = async (flags = '') => {
  await page.goto(`${base}?run=${crypto.randomUUID()}${flags}`)
  await button(chat, 'Practice').waitFor()
  await page.waitForFunction(() => window.practiceTest.state().studyScope !== undefined)
}
const ready = async () => {
  if (await practice.getByLabel('Your topic', { exact: true }).isVisible()) await choosePracticeTopic(page)
  await practice.getByLabel('Your answer', { exact: true }).waitFor()
  await idlePractice(page)
}
const state = () => page.evaluate(() => window.practiceTest.state())
const activeSession = async () => { const { practice } = await state(); return practice.sessions.find(s => s.id === practice.activeSessionId) }
const respondToDialog = (accept, pattern) => {
  page.once('dialog', async dialog => {
    assert.match(dialog.message(), pattern)
    if (accept) await dialog.accept()
    else await dialog.dismiss()
  })
}
try {
  await initial()
  const chatPoems = chat.locator('.study-collection').filter({ has: page.getByLabel('Poems', { exact: true }) })
  const practicePoems = practice.locator('.study-collection').filter({ has: page.getByLabel('Poems', { exact: true }) })
  await chatPoems.locator('summary').click()
  const chatFooter = await chat.locator('.chat-sidebar-footer').boundingBox()
  const chatNew = await button(chat, 'New Chat').boundingBox()
  await button(chat, 'View Log').click()
  const log = page.getByRole('region', { name: 'TokenSmith log', exact: true })
  await log.getByText('Fixture practice question', { exact: true }).waitFor()
  await button(log, 'Close log').click()
  await button(chat, 'Practice').click()
  await ready()
  assert.equal(await practicePoems.locator('details').getAttribute('open'), null)
  await practicePoems.locator('summary').click()
  const original = await activeSession()
  assert.deepEqual(await practice.locator('.chat-sidebar-footer').boundingBox(), chatFooter)
  assert.deepEqual(await button(practice, 'New practice').boundingBox(), chatNew)
  await button(practice, 'View Log').click()
  await log.getByText('Fixture model reply', { exact: true }).waitFor()
  assert.equal(await log.count(), 1)
  await button(log, 'Refresh log').click()
  await page.waitForFunction(() => window.practiceTest.calls.filter(c => c.kind === 'log').length === 3)
  await button(log, 'Close log').click()

  await button(practice, `Rename ${original.title}`).click()
  await practice.getByLabel('Practice name').fill('Canceled rename')
  await practice.getByLabel('Practice name').press('Escape')
  assert.equal((await activeSession()).title, original.title)
  await button(practice, `Rename ${original.title}`).click()
  await practice.getByLabel('Practice name').fill('  ')
  await practice.getByLabel('Practice name').press('Enter')
  assert.equal((await activeSession()).title, original.title)
  await button(practice, `Rename ${original.title}`).click()
  await practice.getByLabel('Practice name').fill('  Insertion practice  ')
  await practice.getByLabel('Practice name').press('Enter')
  await page.waitForFunction(() => window.practiceTest.state().practice.sessions[0].title === 'Insertion practice')
  const titleBounds = await sidebar(practice).locator('.conversation-select > span').boundingBox()
  const actionBounds = await sidebar(practice).locator('.conversation-actions').boundingBox()
  assert.ok(titleBounds.x + titleBounds.width <= actionBounds.x, 'Session titles must not overlap rename/delete controls')
  await answerThenReview(page, 'False')
  await page.screenshot({ path: `${output}/practice-desktop.png` })

  // Open/closed panels are one shared preference, not separate per-mode layouts.
  await button(practice, 'Toggle Library').click()
  await button(practice, 'Toggle history').click()
  await button(practice, 'Chat').click()
  assert.notEqual(await chatPoems.locator('details').getAttribute('open'), null)
  assert.equal(await sidebar(chat).count(), 0)
  assert.equal(await chat.getByRole('complementary', { name: 'Library' }).isVisible(), false)
  await button(chat, 'Toggle history').click()
  await button(chat, 'Practice').click()
  assert.equal(await sidebar(practice).isVisible(), true)
  assert.equal(await practice.getByRole('complementary', { name: 'Library' }).isVisible(), false)
  assert.equal(await practice.getByRole('button', { name: 'False', exact: true }).evaluate(el => el.getAttribute('aria-pressed') === 'true'), true)
  await button(practice, 'Toggle Library').click()
  await button(practice, 'Chat').click()
  assert.equal(await chat.getByRole('complementary', { name: 'Library' }).isVisible(), true)
  await button(chat, 'Rename New Study Chat').click()
  await chat.getByLabel('Chat name').fill('Saved chat')
  await chat.getByLabel('Chat name').press('Enter')
  await button(chat, 'Rename Saved chat').waitFor()
  await chat.getByLabel('Message', { exact: true }).fill('Keep my chat draft.')
  await page.screenshot({ path: `${output}/chat-desktop.png` })
  await button(chat, 'Practice').click()

  // Destructive actions always confirm, affect only this mode, and preserve other history.
  respondToDialog(false, /Delete.*Insertion practice/)
  await button(practice, 'Delete Insertion practice').click()
  assert.equal((await activeSession()).id, original.id)
  respondToDialog(false, /Clear all practice/)
  await button(practice, 'Clear Practice History').click()
  assert.equal((await activeSession()).id, original.id)
  await button(sidebar(practice), 'New practice').click()
  await ready()
  const disposable = await activeSession()
  respondToDialog(true, /Delete.*practice answers/)
  await button(practice, `Delete ${disposable.title}`).click()
  await page.waitForFunction(id => !window.practiceTest.state().practice.sessions.some(s => s.id === id), disposable.id)
  await ready()
  assert.equal((await state()).practice.sessions.some(s => s.id === original.id), true)
  const previousIds = (await state()).practice.sessions.map(s => s.id)
  respondToDialog(true, /Clear all practice.*chats will not be changed/)
  await button(practice, 'Clear Practice History').click()
  await ready()
  assert.equal((await state()).practice.sessions.length, 1)
  assert.equal(previousIds.includes((await activeSession()).id), false)
  assert.equal((await state()).conversations.some(c => c.title === 'Saved chat'), true)
  const practiceId = (await activeSession()).id
  await button(practice, 'Chat').click()
  assert.equal(await chat.getByLabel('Message', { exact: true }).inputValue(), 'Keep my chat draft.')
  respondToDialog(true, /Clear all chats/)
  await button(chat, 'Clear All Chats').click()
  assert.equal((await state()).practice.sessions[0].id, practiceId)

  // Clearing a pending Practice request must not resurrect its deleted session.
  await initial('&slow-model')
  await button(chat, 'Practice').click()
  await choosePracticeTopic(page)
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'true_false_question'))
  const pendingId = (await activeSession()).id
  respondToDialog(true, /Clear all practice/)
  await button(practice, 'Clear Practice History').click()
  await ready()
  assert.equal((await state()).practice.sessions.length, 1)
  assert.notEqual((await activeSession()).id, pendingId)
  assert.equal(await page.evaluate(() => window.practiceTest.calls.some(c => c.kind === 'cancel')), true)

  // Log errors can be retried from either mode without a second viewer.
  await initial('&log-error')
  await button(chat, 'Practice').click()
  await ready()
  await button(practice, 'View Log').click()
  await log.getByText('Test log read failed.', { exact: true }).waitFor()
  await button(log, 'Refresh log').click()
  await log.getByText('Fixture practice question', { exact: true }).waitFor()
  await button(log, 'Close log').click()

  await page.setViewportSize({ width: 860, height: 900 })
  await initial()
  assert.equal(await sidebar(chat).isVisible(), true)
  await button(chat, 'Practice').click()
  await ready()
  assert.equal(await sidebar(practice).isVisible(), true)
  await page.screenshot({ path: `${output}/practice-tablet.png` })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)

  await page.setViewportSize({ width: 390, height: 844 })
  await initial()
  await button(chat, 'Toggle history').click()
  const mobileFooter = await chat.locator('.chat-sidebar-footer').boundingBox()
  await button(chat, 'Practice').click()
  await ready()
  assert.equal(await sidebar(practice).isVisible(), true)
  assert.deepEqual(await practice.locator('.chat-sidebar-footer').boundingBox(), mobileFooter)
  await page.screenshot({ path: `${output}/practice-mobile.png` })
  await button(practice, 'View Log').click()
  await log.getByText('Fixture practice question', { exact: true }).waitFor()
  await page.screenshot({ path: `${output}/log-mobile.png` })
  const bounds = await log.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y + bounds.height <= 844)
  assert.ok(await log.evaluate(el => el.scrollWidth <= el.clientWidth), 'Log contents must fit the small-screen viewer')
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  assert.deepEqual(errors, [])
  console.log('Shared sidebar passed: matching controls/layout, View Log/refresh/errors in both modes, rename/cancel, delete/clear isolation, pending cancellation, shared panels, and mobile layout.')
  console.log(`Screenshots: ${output}`)
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` })
  console.error(await page.locator('body').innerText())
  throw error
} finally { await browser.close() }
