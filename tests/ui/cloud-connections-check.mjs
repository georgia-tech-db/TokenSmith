import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(10000)
const base = process.env.CLOUD_UI_URL || 'http://127.0.0.1:5193/tests/ui/cloud-generators.html'
const output = '/tmp/tokensmith-cloud-connections-ui'
await mkdir(output, { recursive: true })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const chat = page.locator('.chat-frame')
const sheet = page.getByRole('dialog')
const saved = () => page.evaluate(() => window.cloudTest.state())
const connect = async (name, role = 'generator', key) => {
  await chat.getByRole('button', { name: 'Choose chat model', exact: true }).click()
  await chat.locator('.chat-model-menu').getByRole('button', { name: 'Connect a cloud model', exact: true }).click()
  await sheet.getByRole('button', { name: /^OpenAI Connect with/ }).click()
  await sheet.getByLabel('Model type', { exact: true }).selectOption(role)
  if (key) await sheet.getByLabel('OpenAI API key', { exact: true }).fill(key)
  else await sheet.getByText('Using your saved connection', { exact: false }).waitFor()
  await sheet.getByRole('button', { name: 'Connect and find models', exact: true }).click()
  await sheet.getByRole('radio', { name, exact: true }).check()
  await sheet.getByRole('button', { name: 'Use this model', exact: true }).click()
  await sheet.waitFor({ state: 'hidden' })
  await page.waitForFunction(name => window.cloudTest.state().models.some(m => m.remoteModelName === name), name)
}
const settings = async name => {
  await page.getByRole('button', { name: 'Models', exact: true }).click()
  const card = page.locator('.cloud-generator-entry').filter({ has: page.getByRole('heading', { name, exact: true }) })
  await card.getByRole('button', { name: /Connection settings|Reconnect/, exact: true }).click()
}
try {
  await page.goto(`${base}?persist`)
  await connect('gpt-4.1-mini', 'generator', 'demo-key')
  await connect('gpt-4.1')
  const beforeEmbedding = await saved()
  await connect('text-embedding-test', 'embedder')
  const state = await saved()
  const cloud = state.models.filter(m => m.providerId === 'openai')
  assert.equal(cloud.length, 3)
  assert.equal(new Set(cloud.map(m => m.connectionId)).size, 1)
  assert.equal(state.conversations.find(c => c.id === state.activeConversationId).modelId,
    beforeEmbedding.conversations.find(c => c.id === beforeEmbedding.activeConversationId).modelId)
  assert.equal(state.settings.application.defaultModelId, 'gemma')
  assert.equal(state.selectedEmbeddingModelId, cloud.find(m => m.role === 'embedder').id)
  assert.equal('selectedModelId' in state, false)
  assert.equal(JSON.stringify(state).includes('demo-key'), false)
  const connection = cloud[0].connectionId
  const calls = await page.evaluate(() => window.cloudTest.calls)
  assert.ok(calls.filter(c => c.kind === 'connect').slice(1).every(c => c.input.connectionId === connection && c.input.apiKey === ''))

  await settings('text-embedding-test')
  assert.equal(await sheet.getByLabel('Model type').isDisabled(), true)
  await sheet.getByText('Key and storage changes apply to all 3 models using this connection.').waitFor()
  await sheet.getByRole('button', { name: 'Change key', exact: true }).click()
  await sheet.getByLabel('OpenAI API key').fill('replacement-key')
  await sheet.getByRole('button', { name: 'Connect and find models', exact: true }).click()
  await sheet.getByRole('radio', { name: 'text-embedding-test', exact: true }).check()
  await sheet.getByRole('button', { name: 'Use this model', exact: true }).click()
  await sheet.waitFor({ state: 'hidden' })
  assert.equal((await saved()).models.filter(m => m.providerId === 'openai').length, 3)
  assert.equal((await saved()).selectedEmbeddingModelId, state.selectedEmbeddingModelId)

  await settings('gpt-4.1')
  await sheet.getByRole('button', { name: 'Forget key', exact: true }).click()
  await sheet.getByRole('heading', { name: 'Forget OpenAI API key?', exact: true }).waitFor()
  await page.screenshot({ path: `${output}/forget-desktop.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: `${output}/forget-mobile.png` })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await sheet.getByRole('button', { name: 'Keep key', exact: true }).click()
  assert.equal(await page.evaluate(() => window.cloudTest.calls.filter(c => c.kind === 'forget').length), 0)
  await sheet.getByRole('button', { name: 'Forget key', exact: true }).click()
  await sheet.getByRole('button', { name: 'Forget key', exact: true }).click()
  // Closing the sheet while removal finishes must still disconnect every model.
  await sheet.getByRole('button', { name: 'Close cloud setup', exact: true }).click()
  await page.waitForFunction(() => window.cloudTest.state().models.filter(m => m.providerId === 'openai').every(m => m.status === 'needsRuntime'))
  const afterForget = await saved()
  assert.equal(afterForget.selectedEmbeddingModelId, state.selectedEmbeddingModelId)
  assert.equal(afterForget.settings.application.defaultModelId, 'gemma')
  assert.deepEqual(afterForget.conversations.map(c => [c.id, c.modelId]), state.conversations.map(c => [c.id, c.modelId]))
  await page.setViewportSize({ width: 1440, height: 1000 })
  const embeddingCard = page.locator('.cloud-generator-entry').filter({ has: page.getByRole('heading', { name: 'text-embedding-test', exact: true }) })
  assert.match(await embeddingCard.innerText(), /Embedding model/)
  await page.reload()
  await chat.getByRole('button', { name: 'Choose chat model', exact: true }).waitFor()
  assert.equal((await saved()).selectedEmbeddingModelId, state.selectedEmbeddingModelId)
  await page.locator('.rail-nav').getByRole('button', { name: 'Library', exact: true }).click()
  await page.getByRole('button', { name: 'Add folder', exact: true }).click()
  await page.getByPlaceholder('Folder or file path', { exact: true }).fill('/test-book')
  await page.getByRole('button', { name: 'Add and prepare', exact: true }).click()
  await page.getByText('Reconnect your search model in Models, or choose an available embedding model in Settings below.', { exact: true }).waitFor()
  assert.equal((await saved()).materials.length, state.materials.length, 'Must not silently prepare with the local embedder')
  await settings('gpt-4.1')
  await sheet.getByLabel('OpenAI API key').fill('reconnected-key')
  await sheet.getByRole('button', { name: 'Connect and find models', exact: true }).click()
  await sheet.getByRole('radio', { name: 'gpt-4.1', exact: true }).check()
  await sheet.getByRole('button', { name: 'Use this model', exact: true }).click()
  await sheet.waitFor({ state: 'hidden' })
  await page.waitForFunction(() => window.cloudTest.state().models.filter(m => m.providerId === 'openai').every(m => m.status === 'ready'))
  assert.equal((await saved()).selectedEmbeddingModelId, state.selectedEmbeddingModelId)
  assert.equal((await saved()).models.filter(m => m.providerId === 'openai').length, 3)
  assert.deepEqual(errors, [])
  console.log('Cloud connection UI passed: shared chat/embedding key, independent selections, replacement, confirmed removal, close-during-forget, reconnect, desktop and mobile.')
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` })
  throw error
} finally { await browser.close() }
