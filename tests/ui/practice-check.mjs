const checkFeedbackTypography = async () => {
  const feedback = practice.getByRole('region', { name: 'Practice feedback', exact: true }).last()
  const sizes = await feedback.evaluate(element => {
    const heading = getComputedStyle(element.querySelector('.practice-feedback-details h3'))
    const body = getComputedStyle(element.querySelector('.practice-feedback-details .message-text'))
    const section = getComputedStyle(element.querySelector('.practice-feedback-details > section'))
    return { heading: parseFloat(heading.fontSize), body: parseFloat(body.fontSize),
      top: parseFloat(heading.marginTop), bottom: parseFloat(heading.marginBottom), sectionMargin: section.margin }
  })
  assert.ok(sizes.heading <= sizes.body, 'Feedback labels must not be larger than the explanation')
  assert.equal(sizes.top, 0)
  assert.ok(sizes.bottom <= sizes.body / 4, 'Feedback labels should stay close to their explanation')
  assert.equal(sizes.sectionMargin, '0px')
  return sizes
}
