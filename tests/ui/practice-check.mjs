import { choosePracticeTopic, idlePractice, reviewPracticeQuestion, answerThenReview, advancePractice } from './practice-topic-helpers.mjs'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

// Real app, isolated state and deterministic replies; no user data or model calls.
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH })
const base = process.env.PRACTICE_UI_URL || 'http://127.0.0.1:5188/tests/ui/practice.html'
const output = process.env.PRACTICE_UI_OUTPUT || '/tmp/tokensmith-practice-ui'
await mkdir(output, { recursive: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(10000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
const practice = page.locator('.practice-frame')
const chat = page.locator('.chat-frame')
const button = (frame, name) => frame.getByRole('button', { name, exact: true })
const composer = practice.locator('.practice-composer')
const state = () => page.evaluate(() => window.practiceTest.state())
const session = async () => { const s = (await state()).practice; return s.sessions.find(x => x.id === s.activeSessionId) }
const conversation = async () => { const s = await state(); return s.conversations.find(x => x.id === s.activeConversationId) }
const calls = () => page.evaluate(() => window.practiceTest.calls)
const idle = () => idlePractice(page)
const open = async (flags = '') => {
  await page.goto(`${base}?run=${crypto.randomUUID()}&practice&show-sources${flags}`)
  await choosePracticeTopic(page)
  await practice.getByLabel('Your answer', { exact: true }).waitFor()
  await idle()
}
const next = count => advancePractice(page, count)
try {
  for (const [name, width, height] of [['desktop', 1440, 1000], ['mobile', 390, 844]]) {
    await page.setViewportSize({ width, height })
    await page.goto(`${base}?run=${crypto.randomUUID()}&show-sources`)
    await button(chat, 'Practice').waitFor()
    if (width < 800) await button(chat, 'Toggle Library').click()
    await chat.getByLabel('Buffer pool.txt', { exact: true }).uncheck()
    if (width < 800) await button(chat, 'Close Library').click()
    await chat.getByLabel('Message', { exact: true }).fill('Keep this chat draft.')
    await button(chat, 'Practice').click()
    await choosePracticeTopic(page)
    await practice.getByLabel('Your answer', { exact: true }).waitFor()
    await idle()
    const original = await session()
    assert.deepEqual(original.documents.map(d => d.documentId), [1])
    assert.equal(await button(practice, 'Next question').count(), 0, 'Practice advances from the answer choices')
    assert.equal(await practice.getByRole('button', { name: /^(Hint|Explanation|Try again|Ask for help|Check answer)$/ }).count(), 0)
    assert.equal(await practice.locator('.practice-study-actions button').count(), 1)
    const before = (await calls()).length
    await answerThenReview(page, 'False')
    await practice.getByRole('region', { name: 'Practice feedback' }).waitFor()
    assert.equal((await calls()).length, before + 1, 'Only the next question calls the model')
    assert.equal(await button(practice, 'True').isDisabled(), true)
    assert.equal((await session()).questions[0].attempts.length, 1)
    assert.equal((await session()).questions[0].attempts[0].assisted, false)
    const savedAttempt = (await session()).questions[0].attempts[0]
    await page.screenshot({ path: `${output}/feedback-${name}.png` })
    const practiceStyle = await button(practice, 'Chat about this question').evaluate(el => {
      const s = getComputedStyle(el); return [s.borderRadius, s.padding, s.fontSize, s.fontWeight, s.borderWidth]
    })
    await button(practice, 'Chat about this question').click()
    await chat.waitFor({ state: 'visible' })
    await chat.getByRole('region', { name: 'Suggested practice follow-up questions' }).getByRole('button', { name: 'Why record ancestors during insertion?', exact: true }).waitFor()
    const copied = await conversation()
    assert.equal(copied.messages.length, 2)
    assert.match(copied.messages[0].text, /True\/False:.*\n\nMy answer: False/)
    assert.match(copied.messages[1].text, /^Incorrect\n\nRecord each internal node/)
    assert.equal(copied.messages[1].sources[0].documentId, 1)
    assert.deepEqual(copied.documentScope, [{ materialId: 'c1', documentId: 1 }])
    assert.equal((await calls()).filter(c => c.kind === 'discussion').length, 0, 'Copying does not regenerate the answer')
    const suggestion = (await calls()).filter(c => c.kind === 'suggestions').at(-1).request
    assert.deepEqual(suggestion.messages, copied.messages)
    assert.deepEqual(suggestion.retrievedSources, copied.practiceReference.sources)
    assert.equal(copied.practiceSuggestions.length, 3)
    assert.deepEqual((await session()).questions[0].attempts, [savedAttempt])
    assert.equal(await chat.getByLabel('Message', { exact: true }).evaluate(el => el === document.activeElement), true)
    const simplify = button(chat, 'Explain more simply')
    const practiceTopic = button(chat, 'Practice this topic')
    assert.equal(await simplify.count(), 1)
    assert.equal(await practiceTopic.isEnabled(), true)
    const chatStyle = await simplify.evaluate(el => {
      const s = getComputedStyle(el); return [s.borderRadius, s.padding, s.fontSize, s.fontWeight, s.borderWidth]
    })
    assert.deepEqual(practiceStyle, chatStyle)
    await page.screenshot({ path: `${output}/copied-chat-${name}.png` })
    await chat.getByRole('button', { name: 'Why record ancestors during insertion?', exact: true }).click()
    await page.waitForFunction(id => window.practiceTest.state().conversations.find(c => c.id === id)?.messages.length === 4, copied.id)
    const request = (await calls()).filter(c => c.kind === 'discussion').at(-1).request
    assert.ok(request.messages.some(m => m.id === copied.messages[0].id))
    assert.ok(request.messages.some(m => m.id === copied.messages[1].id))
    assert.deepEqual(request.retrievedSources.map(s => s.documentId), [1])
    await practiceTopic.last().click()
    await practice.waitFor({ state: 'visible' })
    await practice.getByLabel('Your answer', { exact: true }).waitFor()
    await idle()
    assert.notEqual((await session()).id, original.id, 'Each Chat topic creates focused practice')
    assert.equal((await session()).topic.question, 'Why record ancestors during insertion?')
    assert.equal((await session()).topic.answer, 'The path tells insertion where to propagate a split without searching from the root again.')
    assert.match(await practice.locator('.practice-topic-reference').innerText(), /Why record ancestors during insertion/)
    assert.equal((await session()).questions.length, 1)
    await next(2)
    assert.equal((await session()).questions.length, 2)
    assert.equal((await state()).practice.sessions.find(s => s.id === original.id).questions[0].attempts.length, 1)
    await page.reload()
    await practice.getByLabel('Your answer', { exact: true }).waitFor()
    assert.equal((await session()).currentIndex, 1)
    const transcript = await practice.locator('.conversation-viewport').boundingBox()
    const input = await composer.boundingBox()
    assert.ok(transcript.height > 180 && transcript.y + transcript.height <= input.y + 1)
    assert.ok(input.y + input.height <= height)
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  }

  // Topic suggestions require one model call, stay cached, and never auto-start a quiz.
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`${base}?run=${crypto.randomUUID()}&practice`)
  await practice.getByRole('group', { name: 'Suggested topics' }).getByRole('button', { name: 'B+ trees', exact: true }).waitFor()
  assert.equal((await calls()).filter(c => c.kind === 'topics').length, 1)
  assert.equal((await calls()).filter(c => c.kind === 'true_false_question').length, 0)
  await page.screenshot({ path: `${output}/topic-picker.png` })
  await button(practice, 'B+ trees').click()
  await practice.getByLabel('Your answer', { exact: true }).waitFor()
  await idle()
  await next(2)
  assert.equal((await calls()).filter(c => c.kind === 'search').length, 1, 'Reuse retrieved topic passages')
  assert.equal((await calls()).filter(c => c.kind === 'sources').length, 0, 'Never sample unrelated whole-document passages')
  assert.ok((await calls()).filter(c => c.kind === 'true_false_question').every(c => JSON.parse(c.request.prompt).topic === 'B+ trees'))
  await button(practice, 'Practice another topic').click()
  await button(practice, 'B+ trees').waitFor()
  assert.equal((await calls()).filter(c => c.kind === 'topics').length, 1)
  await page.reload()
  await button(practice, 'B+ trees').waitFor()
  assert.equal((await calls()).filter(c => c.kind === 'topics').length, 0, 'Topic list survives reload')
  await practice.getByLabel('Buffer pool.txt', { exact: true }).uncheck()
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'topics'))
  assert.deepEqual((await calls()).filter(c => c.kind === 'topic-sources').at(-1).selected.map(d => d.documentId), [1])
  await choosePracticeTopic(page, 'Custom insertion topic')
  await practice.getByLabel('Your answer', { exact: true }).waitFor()
  await idle()
  assert.equal((await session()).topic.title, 'Custom insertion topic')

  // The shortcut uses today's selection, not every folder or sources from the old answer.
  await page.setViewportSize({ width: 1440, height: 1000 })
  await open()
  await answerThenReview(page, 'True')
  await button(practice, 'Chat about this question').click()
  await chat.getByLabel('Database Systems', { exact: true }).uncheck()
  assert.equal(await button(chat, 'Practice this topic').isDisabled(), true)
  await chat.getByLabel('Poems.md', { exact: true }).check()
  await button(chat, 'Practice this topic').click()
  await practice.getByLabel('Your answer', { exact: true }).waitFor()
  await idle()
  assert.deepEqual((await session()).documents.map(d => d.documentId), [3])
  assert.deepEqual((await calls()).filter(c => c.kind === 'search').at(-1).options.documents.map(d => d.documentId), [3])

  // Copying an unanswered question must not disclose its hidden answer guide.
  await open()
  await button(practice, 'Chat about this question').click()
  assert.equal((await conversation()).messages.length, 1)
  assert.doesNotMatch(JSON.stringify((await conversation()).messages), /Record each internal node|correctAnswer/)
  await button(chat, 'Practice').click()
  await answerThenReview(page, 'True')
  assert.equal((await session()).questions[0].attempts[0].assisted, true)

  // Selecting text from an earlier exercise opens Chat with that question, not the latest one.
  await open()
  const firstId = (await session()).questions[0].id
  await next(2)
  const selectable = practice.locator('.practice-thread-question').first().locator('[data-chat-selectable] .message-text').first()
  await selectable.scrollIntoViewIfNeeded()
  await selectable.click()
  await selectable.evaluate(element => {
    document.activeElement?.blur()
    const range = document.createRange(); range.selectNodeContents(element)
    const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range)
    document.dispatchEvent(new Event('selectionchange'))
  })
  await page.locator('.selection-chat-action').click()
  await chat.waitFor({ state: 'visible' })
  assert.equal((await conversation()).practiceReference.questionId, firstId)
  assert.equal((await session()).currentIndex, 0)
  assert.match(await chat.locator('.composer').innerText(), /True\/False:/)
  await button(chat, 'Remove selected passage').click()
  assert.equal(await chat.getByLabel('Message', { exact: true }).inputValue(), '')

  // Next errors and exhaustion preserve the checked answer and never loop automatically.
  await open('&error-next')
  await answerThenReview(page, 'True')
  await practice.getByRole('alert').waitFor()
  assert.equal((await session()).questions.length, 1)
  assert.equal((await session()).questions[0].attempts.length, 1)
  await button(practice, 'Retry question').click()
  await page.waitForFunction(() => window.practiceTest.state().practice.sessions[0].questions.length === 2)
  await idle()
  await open('&duplicate-question')
  await button(practice, 'True').click()
  await practice.getByRole('alert').waitFor()
  assert.match(await practice.getByRole('alert').innerText(), /repeated an earlier question/)
  assert.equal((await session()).questions.length, 1)
  assert.equal((await calls()).filter(c => c.kind === 'true_false_question').length, 2)

  // Stopped requests cannot publish late questions; failure requires an explicit retry.
  await page.goto(`${base}?run=${crypto.randomUUID()}&practice&slow-sources`)
  await choosePracticeTopic(page)
  await page.locator('.generation-status').getByRole('button', { name: 'Stop', exact: true }).click()
  await page.waitForTimeout(2300)
  assert.equal((await calls()).filter(c => c.kind === 'true_false_question').length, 0)
  await button(practice, 'Retry question').waitFor()
  await page.goto(`${base}?run=${crypto.randomUUID()}&practice&error-first`)
  await choosePracticeTopic(page)
  await practice.getByRole('alert').waitFor()
  await button(practice, 'Retry question').click()
  await practice.getByLabel('Your answer', { exact: true }).waitFor()
  assert.equal((await session()).questions.length, 1)
  // Follow-ups can fail/retry, survive reload, and must not publish after cancellation.
  await open('&error-suggestions')
  await answerThenReview(page, 'True')
  await button(practice, 'Chat about this question').click()
  await button(chat, 'Retry suggestions').waitFor()
  assert.equal((await conversation()).messages.length, 2)
  await button(chat, 'Retry suggestions').click()
  await chat.getByRole('button', { name: 'Why record ancestors during insertion?', exact: true }).waitFor()
  const savedChat = await conversation()
  await page.reload()
  await button(chat, savedChat.title).click()
  await chat.getByRole('button', { name: 'Why record ancestors during insertion?', exact: true }).waitFor()
  assert.equal((await calls()).filter(c => c.kind === 'suggestions').length, 0, 'Saved follow-ups need no new call')
  await open('&slow-suggestions')
  await button(practice, 'Chat about this question').click()
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'suggestions'))
  const pendingChat = (await conversation()).id
  await button(chat, 'Practice').click()
  await page.waitForTimeout(2200)
  assert.equal((await state()).conversations.find(c => c.id === pendingChat).practiceSuggestions, undefined)
  assert.ok((await calls()).some(c => c.kind === 'cancel-suggestions'))
  assert.deepEqual(errors, [])
  console.log('Practice/Chat passed: local checking and automatic next question, copied question/answer/sources, follow-up context, scoped practice shortcut, no hidden-key disclosure, errors, cancellation, reload, desktop/mobile.')
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` })
  console.error(await page.locator('body').innerText())
  throw error
} finally { await browser.close() }
