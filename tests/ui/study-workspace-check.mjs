import { choosePracticeTopic, idlePractice, reviewPracticeQuestion, answerThenReview, advancePractice } from './practice-topic-helpers.mjs'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH })
const base = process.env.PRACTICE_UI_URL || 'http://127.0.0.1:5188/tests/ui/practice.html'
const output = '/tmp/tokensmith-study-workspace-ui'
await mkdir(output, { recursive: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(10000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
const chat = page.locator('.chat-frame')
const practice = page.locator('.practice-frame')
const pane = frame => frame.getByRole('complementary', { name: 'Library' })
const initial = async (suffix = '') => {
  await page.goto(`${base}?run=${crypto.randomUUID()}${suffix}`)
  await chat.getByRole('button', { name: 'Toggle Library' }).waitFor()
  await page.waitForFunction(() => window.practiceTest.state().studyScope !== undefined)
}
const savedScope = async expected => page.waitForFunction(ids => {
  const state = window.practiceTest.state()
  return JSON.stringify(state.studyScope?.map(d => d.documentId).sort()) === JSON.stringify(ids) &&
    JSON.stringify(state.practice.draftScope?.map(d => d.documentId).sort()) === JSON.stringify(ids)
}, expected)
const questionReady = async () => {
  if (await practice.getByLabel('Your topic', { exact: true }).isVisible()) await choosePracticeTopic(page)
  await practice.getByLabel('Your answer', { exact: true }).waitFor()
  await idlePractice(page)
}
const activeSession = () => page.evaluate(() => {
  const { practice } = window.practiceTest.state()
  return practice.sessions.find(s => s.id === practice.activeSessionId)
})
try {
  await initial('&suggestions')
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'suggestions'))
  await pane(chat).getByLabel('Buffer pool.txt', { exact: true }).uncheck()
  assert.equal(await pane(chat).getByLabel('Database Systems', { exact: true }).evaluate(el => el.indeterminate), true)
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'suggestions' && c.request.documents.length === 1))
  await savedScope([1])
  await chat.getByLabel('Message', { exact: true }).fill('Why track ancestors?')
  await chat.getByLabel('Message', { exact: true }).press('Shift+Enter')
  assert.equal(await chat.getByLabel('Message', { exact: true }).inputValue(), 'Why track ancestors?\n')
  assert.equal(await page.evaluate(() => window.practiceTest.calls.filter(call => call.kind === 'discussion').length), 0)
  await chat.getByLabel('Message', { exact: true }).press('Enter')
  await page.waitForFunction(() => window.practiceTest.state().conversations.some(c => c.messages.some(m => m.role === 'assistant')))
  const search = await page.evaluate(() => window.practiceTest.calls.find(c => c.kind === 'search'))
  assert.deepEqual(search.options.documents, [{ materialId: 'c1', documentId: 1 }])
  assert.equal(search.mode, 'hybrid')
  await page.screenshot({ path: `${output}/chat-desktop.png` })
  await chat.getByLabel('Message', { exact: true }).fill('How does that help after a split?')
  await chat.getByRole('button', { name: 'Send message', exact: true }).click()
  await page.waitForFunction(() => window.practiceTest.state().conversations.some(c => c.messages.filter(m => m.role === 'assistant').length === 2))
  await chat.getByRole('navigation', { name: 'Questions in this chat' }).getByRole('button', { name: /^Question 1:/ }).click()
  const questionText = chat.locator('[data-question-id] [data-chat-selectable] .message-text').first()
  await questionText.scrollIntoViewIfNeeded()
  await questionText.click()
  await questionText.evaluate(element => {
    document.activeElement?.blur()
    const range = document.createRange(); range.selectNodeContents(element)
    const selection = getSelection(); selection.removeAllRanges(); selection.addRange(range)
    document.dispatchEvent(new Event('selectionchange'))
  })
  await page.locator('.selection-chat-action').click()
  assert.match(await chat.locator('.composer').innerText(), /Why track ancestors/)
  await chat.getByRole('button', { name: 'Remove selected passage' }).click()

  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  assert.equal(await pane(practice).getByLabel('Trees.md', { exact: true }).isChecked(), true)
  assert.equal(await pane(practice).getByLabel('Buffer pool.txt', { exact: true }).isChecked(), false)
  await questionReady()
  assert.equal(await practice.getByText('What would you like to practice?', { exact: true }).count(), 0)
  assert.equal(await practice.getByRole('button', { name: 'Start practice', exact: true }).count(), 0)
  assert.equal(await practice.getByRole('button', { name: 'Choose documents', exact: true }).count(), 0)
  const original = await activeSession()
  await answerThenReview(page, 'False')
  await pane(practice).getByLabel('Trees.md', { exact: true }).uncheck()
  await pane(practice).getByLabel('Poems', { exact: true }).click()
  await questionReady()
  assert.equal(await pane(practice).getByLabel('Poems.md', { exact: true }).isEnabled(), true)
  await savedScope([3])
  assert.deepEqual((await activeSession()).documents.map(d => d.documentId), [3])
  assert.equal(await page.evaluate(id => window.practiceTest.state().practice.sessions.find(s => s.id === id).questions[0].draft, original.id), 'False')
  await page.screenshot({ path: `${output}/practice-desktop.png` })

  await practice.getByRole('button', { name: 'Chat', exact: true }).click()
  assert.equal(await pane(chat).getByLabel('Trees.md', { exact: true }).isChecked(), false)
  assert.equal(await pane(chat).getByLabel('Poems.md', { exact: true }).isChecked(), true)
  await chat.getByRole('button', { name: 'New Chat', exact: true }).click()
  await savedScope([3])
  await chat.getByLabel('Message', { exact: true }).fill('What does this poem mean?')
  await chat.getByRole('button', { name: 'Send message', exact: true }).click()
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'search' && c.options.documents[0]?.documentId === 3))
  await pane(chat).getByLabel('Poems.md', { exact: true }).uncheck()
  await savedScope([])
  await page.reload()
  await savedScope([])
  assert.equal(await pane(chat).getByLabel('Database Systems', { exact: true }).isChecked(), false)
  await chat.getByRole('button', { name: 'Why track ancestors?', exact: true }).click()
  await savedScope([])

  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await practice.getByText('No documents selected.', { exact: true }).waitFor()
  await page.waitForTimeout(500)
  assert.equal(await page.evaluate(() => window.practiceTest.calls.filter(c => c.kind === 'true_false_question').length), 0)
  // Explicitly reopening history restores that session's selection in both modes.
  await practice.getByRole('complementary', { name: 'Practice sessions' }).getByRole('button', { name: 'B+ trees 2 questions', exact: true }).last().click()
  await questionReady()
  assert.equal(await practice.getByRole('button', { name: 'False', exact: true }).evaluate(el => el.getAttribute('aria-pressed') === 'true'), true)
  await savedScope([1])
  assert.equal((await activeSession()).id, original.id)
  assert.equal(await page.evaluate(() => window.practiceTest.calls.filter(c => c.kind === 'true_false_question').length), 0)
  await practice.getByRole('button', { name: 'Chat about this question', exact: true }).click()
  await chat.waitFor({ state: 'visible' })
  assert.equal(await pane(chat).getByLabel('Trees.md', { exact: true }).isChecked(), true)
  await savedScope([1])

  // A rapid scope change cancels the pending question, and only the final scope is published.
  await initial('&slow-model')
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await choosePracticeTopic(page)
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'true_false_question'))
  const abandoned = await activeSession()
  await pane(practice).getByLabel('Database Systems', { exact: true }).uncheck()
  await pane(practice).getByLabel('Poems', { exact: true }).click()
  await questionReady()
  assert.deepEqual((await activeSession()).documents.map(d => d.documentId), [3])
  assert.equal(await page.evaluate(id => window.practiceTest.state().practice.sessions.find(s => s.id === id).questions.length, abandoned.id), 0)
  assert.equal(await page.evaluate(() => window.practiceTest.calls.filter(c => c.kind === 'true_false_question').length), 2)
  assert.equal(await page.evaluate(() => window.practiceTest.calls.some(c => c.kind === 'cancel')), true)
  const resumed = (await activeSession()).id
  await practice.getByRole('button', { name: 'Chat', exact: true }).click()
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await questionReady()
  assert.equal((await activeSession()).id, resumed)
  assert.equal(await page.evaluate(() => window.practiceTest.calls.filter(c => c.kind === 'true_false_question').length), 2)

  // Changing selection in Chat invalidates a hidden Practice request too.
  await initial('&slow-model')
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await choosePracticeTopic(page)
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'true_false_question'))
  await practice.getByRole('button', { name: 'Chat', exact: true }).click()
  await pane(chat).getByLabel('Buffer pool.txt', { exact: true }).uncheck()
  await page.waitForTimeout(2300)
  assert.equal(await page.evaluate(() => window.practiceTest.state().practice.sessions[0].questions.length), 0)
  assert.equal(await page.evaluate(() => window.practiceTest.calls.filter(c => c.kind === 'true_false_question').length), 1)
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await questionReady()
  assert.deepEqual((await activeSession()).documents.map(d => d.documentId), [1])

  // Chat responses from a previous selection must not arrive in the updated workspace.
  await initial('&slow-model')
  await chat.getByLabel('Message', { exact: true }).fill('An answer to cancel.')
  await chat.getByRole('button', { name: 'Send message', exact: true }).click()
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'discussion'))
  await pane(chat).getByLabel('Buffer pool.txt', { exact: true }).uncheck()
  await page.waitForTimeout(2300)
  assert.equal(await page.evaluate(() => window.practiceTest.state().conversations.flatMap(c => c.messages).filter(m => m.role === 'assistant').length), 0)

  await page.setViewportSize({ width: 390, height: 844 })
  await initial()
  assert.equal(await pane(chat).isVisible(), false)
  await chat.getByRole('button', { name: 'Toggle Library' }).click()
  await pane(chat).getByLabel('Buffer pool.txt', { exact: true }).uncheck()
  await page.screenshot({ path: `${output}/chat-materials-mobile.png` })
  const chatHeader = await chat.locator('.study-topbar').boundingBox()
  assert.ok(Math.abs((await pane(chat).boundingBox()).y - chatHeader.y - chatHeader.height) <= 1)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await pane(chat).getByRole('button', { name: 'Close Library' }).click()
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await practice.getByRole('button', { name: 'Toggle Library' }).click()
  assert.equal(await pane(practice).getByLabel('Buffer pool.txt', { exact: true }).isChecked(), false)
  await page.screenshot({ path: `${output}/practice-materials-mobile.png` })
  const practiceHeader = await practice.locator('.study-topbar').boundingBox()
  assert.equal(chatHeader.height, practiceHeader.height)
  await pane(practice).getByRole('button', { name: 'Close Library' }).click()
  await practice.getByRole('button', { name: 'Toggle history' }).click()
  assert.equal(await practice.getByRole('complementary', { name: 'Practice sessions' }).isVisible(), true)

  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`${base}?run=${crypto.randomUUID()}&catalog-error`)
  await pane(chat).getByRole('alert').waitFor()
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await pane(practice).getByRole('alert').waitFor()
  assert.equal(await page.evaluate(() => window.practiceTest.calls.filter(c => c.kind === 'true_false_question').length), 0)
  await page.getByRole('complementary', { name: 'Primary navigation' }).getByRole('button', { name: 'Library', exact: true }).click()
  const library = page.locator('.library-workspace')
  await library.getByRole('heading', { name: 'Library', exact: true }).waitFor()
  assert.equal(await library.getByText('2 folders', { exact: true }).count(), 1)
  await library.getByRole('button', { name: 'Add folder', exact: true }).click()
  await library.getByLabel('Folder name', { exact: false }).waitFor()
  assert.doesNotMatch(await library.innerText(), /Collection|Materials/)
  assert.deepEqual(errors, [])
  console.log('Shared study UI passed: topic selection, shared hybrid/suggestion scope, editable selection, saved history, empty selection, cancellation in either mode, no duplicate starts, desktop and mobile drawers, catalog errors.')
  console.log(`Screenshots: ${output}`)
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` })
  console.error(await page.locator('body').innerText())
  throw error
} finally { await browser.close() }
