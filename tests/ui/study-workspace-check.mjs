import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH })
const base = process.env.PRACTICE_UI_URL || 'http://127.0.0.1:5188/tests/ui/practice.html'
const output = '/tmp/tokensmith-study-workspace-ui'
await mkdir(output, { recursive: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
page.setDefaultTimeout(10000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
const chat = page.locator('.chat-frame')
const practice = page.locator('.practice-frame')
const pane = frame => frame.getByRole('complementary', { name: 'Study materials' })
const initial = async (suffix = '') => {
  await page.goto(`${base}?run=${crypto.randomUUID()}${suffix}`)
  await chat.getByRole('button', { name: 'Toggle materials' }).waitFor()
  await page.waitForFunction(() => window.practiceTest.state().studyScope !== undefined)
}
const savedScope = async expected => page.waitForFunction(ids => {
  const state = window.practiceTest.state()
  return JSON.stringify(state.conversations.find(c => c.id === state.activeConversationId)?.documentScope.map(d => d.documentId).sort()) === JSON.stringify(ids)
}, expected)
try {
  await initial('&suggestions')
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'suggestions'))
  await pane(chat).getByLabel('Buffer pool.txt', { exact: true }).uncheck()
  assert.equal(await pane(chat).getByLabel('Database Systems', { exact: true }).evaluate(el => el.indeterminate), true)
  await page.waitForFunction(() => window.practiceTest.calls.some(c => c.kind === 'suggestions' && c.request.documents.length === 1))
  await savedScope([1])
  await chat.getByLabel('Message', { exact: true }).fill('Why track ancestors?')
  await chat.getByRole('button', { name: 'Send message', exact: true }).click()
  await page.waitForFunction(() => window.practiceTest.state().conversations.some(c => c.messages.some(m => m.role === 'assistant')))
  const search = await page.evaluate(() => window.practiceTest.calls.find(c => c.kind === 'search'))
  assert.deepEqual(search.options.documents, [{ materialId: 'c1', documentId: 1 }])
  assert.equal(search.mode, 'hybrid')
  await page.screenshot({ path: `${output}/chat-desktop.png` })

  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  assert.equal(await pane(practice).getByLabel('Trees.md', { exact: true }).isChecked(), true)
  assert.equal(await pane(practice).getByLabel('Buffer pool.txt', { exact: true }).isChecked(), false)
  await pane(practice).getByLabel('Trees.md', { exact: true }).uncheck()
  await pane(practice).getByLabel('Poems', { exact: true }).check()
  await practice.getByRole('button', { name: 'Start practice', exact: true }).click()
  await practice.getByLabel('Your answer', { exact: true }).waitFor()
  assert.equal(await pane(practice).getByLabel('Poems.md', { exact: true }).isDisabled(), true)
  await page.waitForFunction(() => window.practiceTest.state().practice.sessions.length === 1)
  assert.deepEqual(await page.evaluate(() => window.practiceTest.state().practice.sessions[0].documents.map(d => d.documentId)), [3])
  await page.screenshot({ path: `${output}/practice-desktop.png` })

  await practice.getByRole('button', { name: 'Chat', exact: true }).click()
  assert.equal(await pane(chat).getByLabel('Trees.md', { exact: true }).isChecked(), true)
  assert.equal(await pane(chat).getByLabel('Poems.md', { exact: true }).isChecked(), false)
  await chat.getByRole('button', { name: 'New Chat', exact: true }).click()
  await savedScope([1])
  await pane(chat).getByLabel('Trees.md', { exact: true }).uncheck()
  await savedScope([])
  await page.reload()
  await savedScope([])
  assert.equal(await pane(chat).getByLabel('Database Systems', { exact: true }).isChecked(), false)
  await chat.getByRole('button', { name: 'Why track ancestors?', exact: true }).click()
  await savedScope([1])

  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  assert.equal(await pane(practice).getByLabel('Poems.md', { exact: true }).isChecked(), true)
  await practice.getByRole('button', { name: 'Show explanation', exact: true }).click()
  await practice.getByRole('heading', { name: 'Explanation', exact: true }).waitFor()
  await practice.getByRole('button', { name: 'Discuss this', exact: true }).click()
  await savedScope([3])
  assert.equal(await pane(chat).getByLabel('Poems.md', { exact: true }).isChecked(), true)

  await page.setViewportSize({ width: 390, height: 844 })
  await initial()
  assert.equal(await pane(chat).isVisible(), false)
  await chat.getByRole('button', { name: 'Toggle materials' }).click()
  await pane(chat).getByLabel('Buffer pool.txt', { exact: true }).uncheck()
  await page.screenshot({ path: `${output}/chat-materials-mobile.png` })
  const chatHeader = await chat.locator('.study-topbar').boundingBox()
  assert.ok(Math.abs((await pane(chat).boundingBox()).y - chatHeader.y - chatHeader.height) <= 1)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
  await pane(chat).getByRole('button', { name: 'Close materials' }).click()
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await practice.getByRole('button', { name: 'Toggle materials' }).click()
  assert.equal(await pane(practice).getByLabel('Buffer pool.txt', { exact: true }).isChecked(), false)
  await page.screenshot({ path: `${output}/practice-materials-mobile.png` })
  const practiceHeader = await practice.locator('.study-topbar').boundingBox()
  assert.equal(chatHeader.height, practiceHeader.height)
  await pane(practice).getByRole('button', { name: 'Close materials' }).click()
  await practice.getByRole('button', { name: 'Toggle history' }).click()
  assert.equal(await practice.getByRole('complementary', { name: 'Practice sessions' }).isVisible(), true)

  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`${base}?run=${crypto.randomUUID()}&catalog-error`)
  await pane(chat).getByRole('alert').waitFor()
  await chat.getByRole('button', { name: 'Practice', exact: true }).click()
  await pane(practice).getByRole('alert').waitFor()
  assert.equal(await practice.getByRole('button', { name: 'Start practice' }).isDisabled(), true)
  assert.deepEqual(errors, [])
  console.log('Shared study UI passed: hybrid request scope, initial suggestions, chat restoration, empty-scope persistence, practice lock, discussion scope, desktop and mobile drawers, catalog errors.')
  console.log(`Screenshots: ${output}`)
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` })
  console.error(await page.locator('body').innerText())
  throw error
} finally { await browser.close() }
