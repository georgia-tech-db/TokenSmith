import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { parseArgs } from 'node:util'

const { values } = parseArgs({ options: {
  'user-data': { type: 'string' }, ids: { type: 'string' }, since: { type: 'string' }, out: { type: 'string' }
} })
if (!values['user-data'] || !values.ids || !values.since || !values.out) {
  throw new Error('--user-data, --ids, --since and --out are required')
}
const since = Date.parse(values.since)
if (!Number.isFinite(since)) throw new Error('--since must be a timestamp')
const state = JSON.parse(readFileSync(resolve(values['user-data'], 'tokensmith-state.json'), 'utf8'))
const ids = values.ids.split(',')
const conversations = ids.map((id) => {
  const conversation = state.conversations.find((item) => item.id === id)
  if (!conversation) throw new Error(`Missing conversation ${id}`)
  return conversation
})
const questions = new Set(conversations.flatMap((conversation) => conversation.messages
  .filter((message) => message.role === 'user').map((message) => message.text)))
const entries = readFileSync(resolve(values['user-data'], 'logs', 'tokensmith.log'), 'utf8')
  .split('\n').filter(Boolean).flatMap((line) => {
    try { return [JSON.parse(line)] } catch { return [] }
  }).filter((entry) => Date.parse(entry.time) >= since)
const requestEvents = new Set(['chat_question_rewrite', 'chat_request_context', 'follow_up_suggestions'])
const evidence = entries.filter((entry) => requestEvents.has(entry.event) && questions.has(entry.prompt))
const queries = new Set(evidence.filter((entry) => entry.event === 'chat_request_context').map((entry) => entry.retrievalQuery))
const runtimeEvidence = entries.filter((entry) => entry.event === 'chat_runtime_context_budget' ||
  (['library_search_request', 'library_search_result'].includes(entry.event) && queries.has(entry.query)))
writeFileSync(values.out, JSON.stringify({
  exportedAt: new Date().toISOString(),
  method: 'Actual GUI conversations. Student follow-ups chosen after reading each new model answer; not generated by this exporter. Review notes are separate.',
  selectedModelId: state.selectedModelId, selectedEmbeddingModelId: state.selectedEmbeddingModelId,
  searchMode: state.settings.application.searchMode,
  modelSettings: state.settings.modelSettingsById[state.selectedModelId],
  conversations, evidence, runtimeEvidence
}, null, 2))
console.log(JSON.stringify({ output: values.out, conversations: conversations.length, evidenceEvents: evidence.length }))
